// Rebuilds extension/github-modes.js from GitHub's current theme CSS.
// A dark theme over GitHub's light mode (or the reverse) needs GitHub's own colors for
// that mode, so syntax highlighting, diffs and labels stay readable.
// Run: node scripts/github-modes.mjs
import { writeFile } from "node:fs/promises";

const get = async (url) => {
  const res = await fetch(url, { headers: { "user-agent": "github-reskin" } });
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
};

// Variables from the first rule, which is the mode's full palette.
function variables(css) {
  const body = css.slice(css.indexOf("{") + 1, css.indexOf("}"));
  return Object.fromEntries(
    body
      .split(";")
      .map((part) => /^\s*(--[\w-]+)\s*:\s*(.+?)\s*$/.exec(part))
      .filter(Boolean)
      .map((m) => [m[1], m[2]]),
  );
}

// Every GitHub palette: light, dark, dimmed, high contrast, colorblind and tritanopia.
const html = await get("https://github.com/");
const links = new Map(
  [...html.matchAll(/https:\/\/github\.githubassets\.com\/assets\/((?:light|dark)[a-z_]*)-[0-9a-f]+\.css/g)].map((m) => [m[1], m[0]]),
);
if (!links.has("light") || !links.has("dark")) throw new Error("github.com no longer links its light and dark theme CSS");
const palettes = Object.fromEntries(await Promise.all([...links].map(async ([mode, url]) => [mode, variables(await get(url))])));
const { dark, light } = palettes;

// Copy a variable if any palette disagrees on it, so whichever palette your account uses,
// the standard light or dark value replaces it.
const names = Object.keys(dark).filter(
  (name) => name in light && Object.values(palettes).some((p) => name in p && p[name] !== dark[name]),
);
if (names.length < 100 || Object.keys(palettes).length < 4) {
  throw new Error(`Found ${names.length} variables in ${Object.keys(palettes).length} palettes; GitHub's CSS layout may have changed`);
}

const declarations = (palette) => names.map((name) => `${name}:${palette[name]} !important;`).join("");
const date = new Date().toISOString().slice(0, 10);
await writeFile(
  new URL("../extension/github-modes.js", import.meta.url),
  `// Generated by scripts/github-modes.mjs from GitHub's CSS on ${date}. Do not edit by hand.\n` +
    `globalThis.GitHubReskinModes = ${JSON.stringify({ dark: declarations(dark), light: declarations(light) }, null, 1)};\n`,
);
console.log(`Wrote ${names.length} variables per mode from ${Object.keys(palettes).length} palettes`);
